BEGIN;

-- Serialize schema updates when multiple app instances start together.
SELECT pg_advisory_xact_lock(hashtext('smartcast.schema'));

CREATE TABLE IF NOT EXISTS playlist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    name VARCHAR(120) NOT NULL,

    CONSTRAINT fk_playlist_owner FOREIGN KEY (owner_id)
        REFERENCES app_user (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS playlist_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_id BIGINT NOT NULL,
    material_id BIGINT NOT NULL,
    position INTEGER NOT NULL,

    CONSTRAINT fk_playlist_item_playlist FOREIGN KEY (playlist_id)
        REFERENCES playlist (id) ON DELETE CASCADE,
    CONSTRAINT fk_playlist_item_material FOREIGN KEY (material_id)
        REFERENCES material (id) ON DELETE CASCADE,
    CONSTRAINT uq_playlist_item_material UNIQUE (playlist_id, material_id),
    CONSTRAINT ck_playlist_item_position CHECK (position >= 0)
);

CREATE INDEX IF NOT EXISTS idx_playlist_owner ON playlist (owner_id);
CREATE INDEX IF NOT EXISTS idx_playlist_item_material ON playlist_item (material_id);

COMMIT;

